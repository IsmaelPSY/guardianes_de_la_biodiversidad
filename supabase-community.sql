create table if not exists public.community_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (username ~ '^[a-z0-9_]{3,24}$'),
  display_name text not null check (char_length(display_name) between 1 and 40),
  bio text not null default '' check (char_length(bio) <= 240),
  avatar_path text,
  created_at timestamptz not null default now()
);

create or replace function public.create_community_profile()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.community_profiles (id, username, display_name)
  values (new.id, 'miembro_' || left(replace(new.id::text, '-', ''), 12),
    coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), 'Nuevo miembro'))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_community on auth.users;
create trigger on_auth_user_created_community after insert on auth.users
for each row execute procedure public.create_community_profile();

create table if not exists public.community_posts (
  id bigint generated by default as identity primary key,
  author_id uuid not null references public.community_profiles(id) on delete cascade,
  post_type text not null check (post_type in ('accion','noticia','evento','recomendacion','avistamiento')),
  title text not null check (char_length(title) between 1 and 100),
  body text not null check (char_length(body) between 1 and 1500),
  image_path text,
  created_at timestamptz not null default now()
);
create table if not exists public.community_comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  author_id uuid not null references public.community_profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 500),
  created_at timestamptz not null default now()
);
create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.community_posts(id) on delete cascade,
  reporter_id uuid not null references public.community_profiles(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 300),
  created_at timestamptz not null default now(),
  unique (post_id, reporter_id)
);

create index if not exists community_posts_created_at_idx on public.community_posts (created_at desc);
create index if not exists community_comments_post_idx on public.community_comments (post_id, created_at);

alter table public.community_profiles enable row level security;
alter table public.community_posts enable row level security;
alter table public.community_comments enable row level security;
alter table public.community_reports enable row level security;
revoke all on public.community_profiles, public.community_posts, public.community_comments, public.community_reports from anon, authenticated;
grant select on public.community_profiles, public.community_posts, public.community_comments to anon, authenticated;
grant update (username, display_name, bio, avatar_path) on public.community_profiles to authenticated;
grant insert, update, delete on public.community_posts to authenticated;
grant insert, delete on public.community_comments to authenticated;
grant insert on public.community_reports to authenticated;
grant usage, select on sequence public.community_posts_id_seq, public.community_comments_id_seq, public.community_reports_id_seq to authenticated;

